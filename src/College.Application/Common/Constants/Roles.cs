namespace College.Application.Common.Constants
{
    public static class Roles
    {
        /// <summary>
        /// Leads the university and oversees its colleges and overall operations.
        /// </summary>
        public const string UniversityPresident = "UniversityPresident";

        /// <summary>
        /// Helps lead the university and oversees assigned university sectors.
        /// </summary>
        public const string UniversityVicePresident = "UniversityVicePresident";

        /// <summary>
        /// Oversees the university's administrative work and manages its general affairs.
        /// </summary>
        public const string UniversitySecretaryGeneral = "UniversitySecretaryGeneral";

        /// <summary>
        /// Leads the faculty and oversees its academic and administrative work.
        /// </summary>
        public const string Dean = "Dean";

        /// <summary>
        /// Oversees education, course registration, and student affairs within the faculty.
        /// </summary>
        public const string ViceDeanForEducationAndStudentAffairs = "ViceDeanForEducationAndStudentAffairs";

        /// <summary>
        /// Oversees postgraduate programs, research activities, and related academic affairs.
        /// </summary>
        public const string ViceDeanForPostgraduateStudiesAndResearch = "ViceDeanForPostgraduateStudiesAndResearch";

        /// <summary>
        /// Oversees community services and activities related to environmental development.
        /// </summary>
        public const string ViceDeanForCommunityServiceAndEnvironmentalDevelopment = "ViceDeanForCommunityServiceAndEnvironmentalDevelopment";

        /// <summary>
        /// Handles the faculty's administrative work and supports the dean's office.
        /// </summary>
        public const string FacultySecretary = "FacultySecretary";

        /// <summary>
        /// Manages student records, registration, academic status, and student requests.
        /// </summary>
        public const string StudentAffairsManager = "StudentAffairsManager";

        /// <summary>
        /// Updates student records and handles registration and student requests.
        /// </summary>
        public const string StudentAffairsStaff = "StudentAffairsStaff";

        /// <summary>
        /// Manages alumni records, graduation documents, and services for graduates.
        /// </summary>
        public const string AlumniAffairsManager = "AlumniAffairsManager";

        /// <summary>
        /// Updates alumni records and handles certificate and document requests.
        /// </summary>
        public const string AlumniAffairsStaff = "AlumniAffairsStaff";

        /// <summary>
        /// Manages faculty fees, payments, outstanding balances, and financial records.
        /// </summary>
        public const string FinancialManager = "FinancialManager";

        /// <summary>
        /// Handles student fees, payment records, and other financial procedures.
        /// </summary>
        public const string FinancialStaff = "FinancialStaff";

        /// <summary>
        /// Leads an academic department and oversees its courses, teaching staff, and activities.
        /// </summary>
        public const string DepartmentHead = "DepartmentHead";

        /// <summary>
        /// Delivers lectures, manages course materials, records attendance, and evaluates students.
        /// </summary>
        public const string FacultyMember = "FacultyMember";

        /// <summary>
        /// Conducts practical sessions and tutorials, records attendance, and helps students with their courses.
        /// </summary>
        public const string TeachingAssistant = "TeachingAssistant";

        /// <summary>
        /// Views courses, learning materials, schedules, grades, attendance, payments, and student services.
        /// </summary>
        public const string Student = "Student";
    }
}